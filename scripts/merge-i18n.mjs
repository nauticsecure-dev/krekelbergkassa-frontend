for (const [file, additions] of [
  ['src/i18n/messages/en.json', enAdditions],
  ['src/i18n/messages/de.json', deAdditions],
]) {
  const json = JSON.parse(fs.readFileSync(file, 'utf8'));
  for (const [path, value] of Object.entries(additions)) {
    setPath(json, path, value);
  }
  fs.writeFileSync(file, JSON.stringify(json, null, 2) + '\n');
  console.log(`Updated ${file} with ${Object.keys(additions).length} keys`);
}
